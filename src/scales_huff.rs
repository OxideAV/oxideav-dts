#[cfg(test)]
mod tests {
    use super::*;

    const BOOKS: [(&str, &[HuffmanEntry]); 5] = [
        ("SA129", TABLE_SA129),
        ("SB129", TABLE_SB129),
        ("SC129", TABLE_SC129),
        ("SD129", TABLE_SD129),
        ("SE129", TABLE_SE129),
    ];

    /// Every book covers each difference in -64..=64 exactly once with a complete,
    /// prefix-free code: a transcription slip in any entry breaks one of these sums.
    #[test]
    fn scale_books_are_complete_prefix_codes_over_the_129_differences() {
        for (name, book) in BOOKS {
            assert_eq!(book.len(), 129, "{name}");
            let mut seen = [false; 129];
            let mut kraft = 0.0f64;
            for &(symbol, len, code) in book {
                let slot = usize::try_from(symbol + 64).unwrap();
                assert!(!seen[slot], "{name}: {symbol} twice");
                seen[slot] = true;
                assert!((1..=16).contains(&len), "{name}: {symbol} has {len} bits");
                assert!(
                    u32::from(code) < 1 << len,
                    "{name}: code of {symbol} exceeds {len} bits"
                );
                kraft += 2f64.powi(-i32::from(len));
            }
            assert!(seen.iter().all(|&s| s), "{name}: a difference is missing");
            assert!((kraft - 1.0).abs() < 1e-12, "{name}: Kraft sum {kraft}");
            for &(a, alen, acode) in book {
                for &(b, blen, bcode) in book {
                    if a != b && alen <= blen {
                        assert_ne!(
                            bcode >> (blen - alen),
                            acode,
                            "{name}: code of {a} prefixes {b}'s"
                        );
                    }
                }
            }
        }
    }

    /// Spot values straight from the printed tables (page 219: SA129 level 0 is `01`,
    /// level 2 is `000`, level -64 is 14 bits 15 024).
    #[test]
    fn sa129_matches_the_printed_page() {
        let entry = |symbol: i16| TABLE_SA129.iter().find(|e| e.0 == symbol).copied().unwrap();
        assert_eq!(entry(0), (0, 2, 1));
        assert_eq!(entry(2), (2, 3, 0));
        assert_eq!(entry(-64), (-64, 14, 15024));
    }
}
